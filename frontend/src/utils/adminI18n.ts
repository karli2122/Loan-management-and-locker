export function ta(language: string, key: string, vars?: Record<string, string | number>): string {
  const e = S[key];
  let s = e ? (language === 'et' ? e.et : e.en) : key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
